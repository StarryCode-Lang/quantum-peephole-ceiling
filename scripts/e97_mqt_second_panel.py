"""E97: MQT Bench as a SECOND, independent panel for the rule-utilisation census.

Motivation
----------
Round 23 established two structural claims on the frozen E39/E46 pipeline:
E90 (38,118 windows) found that every *reducing* action has source length 2
and E95 (69 certified escape sources) found that the content-first /
reorder-first split coincides exactly with the root strata.  Both were
measured on one panel generated by this project's own generators.  This
experiment asks whether the same structure appears on a panel that the
project did not generate: MQT Bench circuits (the external-validity source
E71 introduced in round 16), normalized by the same frozen machinery.

Method
------
1. Normalize N MQT Bench circuits (N = 30 = E71's 14 + 16 new algorithms, all
   <= 10 qubits so the project's exact equivalence verifier applies) into the
   frozen basis {h, x, rz, cx} with the panel's own ``normalize_circuit``
   (E71's normalization path, level-0 transpile, no routing semantics).
   Every normalization refusal and every generation failure is recorded
   fail-closed, never dropped.
2. Certify each normalization with the project's equivalence verifier
   (``src.equivalence.certify_equivalence``, exact numerical-unitary scope);
   a census row exists only for a VERIFIED_EQUIVALENT normalization.
3. Root census (the source-level E90 analogue, no windows): at the ROOT state
   of every normalized listing, enumerate every legal action under the
   declared rule scope ``e44_core_v1`` and record actions_total,
   actions_reducing / neutral / positive, the minimum reducing source length,
   the per-rule firing counts, and the family split (quartz / pair_v1 /
   exchange).  Greedy-fixed-point and locally irreducible roots therefore get
   an explicit ``actions_reducing = 0`` row, not an absence.
4. Two-axis partition per circuit (the E95 analogue on this panel): the root
   axis is "reducing-at-root" (content_first) vs "no reducing action at the
   root" (reorder_first_candidate); the certified commutation closure (E56's
   ``closure_run``, the certified replay machinery E71 ran) provides, where it
   reduces cost, a certified reduction witness whose first action classifies
   the escape the same way E95 classified escape witnesses.  Roots are also
   stratum-labelled with the frozen pipeline's own semantics (greedy run iff
   the listing is within ``MAX_BASELINE_GATES``): GREEDY_FIXED_POINT when the
   normalized listing is already a greedy fixed point, GREEDY_REDUCIBLE when
   greedy shrinks it, RAW_NORMALIZED_OVER_BASELINE_BUDGET otherwise.

Contract
--------
Read-only on frozen inputs (rule library sha256-pinned; E71/E90/E95 review
packages read only for cross-references).  The only enumeration is the
legal-action census at the 30 root states plus the certified closure; no
landscape search is re-run.  Nothing under ``data/``, ``release/`` or
``docs/manuscript/`` is written.

Self-checks (exit 1 on any failure)
    * the 30-target list is recorded and every target is accounted for
      (OK / refusal with reason / generation failure with reason);
    * every census row's normalization is VERIFIED_EQUIVALENT (exact
      numerical-unitary certificate from the project's verifier);
    * every reducing action's source length is within the declared scope
      (E90's check: lengths in {2,3,4,5}, rule id resolvable);
    * determinism: the census on the first two circuits is recomputed and
      must reproduce the recorded rows exactly;
    * E71 alignment: for the 14 shared circuits, raw/root/rz/cx/h gate counts
      and the closure output must reproduce E71's published numbers exactly;
    * closure coherence: no positive closure step anywhere; a reducing first
      closure step implies the root census also shows a reducing action; a
      root with no reducing action can only open cost-neutrally.

Outputs (``docs/review/science_boost/2026-11-06_mqt_second_panel/``)
    census_circuit.csv  one row per OK circuit: root census + stratum +
                        closure + equivalence certificate
    partition.csv       one row per circuit: two-axis partition (root axis and
                        witness axis) with the escape subset flagged
    rule_usage.csv      one row per rule id in the declared scope (E90's
                        rule_usage analogue, on this panel)
    summary.json        headline counts, E90/E95 comparisons, self-checks,
                        provenance
    instances/*.qasm    the normalized listings (E71 house pattern)
    MANIFEST.json       sha256 of every artifact
"""

