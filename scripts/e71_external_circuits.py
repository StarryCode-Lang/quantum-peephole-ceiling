"""E69: external circuit set — MQT Bench subset under the frozen basis (P5).

Round-12/13 external-validity requirement: at least one circuit source that
is NOT generated by this project's own generators.  This driver pulls a
small MQT Bench subset (mqt-bench 2.3.0, ALG level), normalizes each circuit
into the frozen basis {h, x, rz, cx} with the panel's own
``normalize_circuit`` (level-0 transpile; no routing semantics), and runs
the certified commutation closure on every normalized listing:

    gates/root, rz/cx split, closure output, reduction, and — for the H-free
    subset — the absolute rotation-gap decomposition against |supp(f)|.

Every normalization refusal is recorded with its reason (fail-closed
reporting, no silent dropping).  Output: dated review-grade package with the
normalized QASM listings, results CSV, and a receipt pinning the mqt-bench
version and the closure engine hashes.

Usage:
    python scripts/e71_external_circuits.py [--deadline 60]
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from qiskit import qasm2  # noqa: E402

from experiments.e45_development_grid.run import normalize_circuit  # noqa: E402
from scripts.e62_rotation_gap import phase_polynomial, segmented_support  # noqa: E402
from scripts.e56_closure_criterion import closure_run  # noqa: E402

EXPERIMENT_ID = "E71_EXTERNAL_CIRCUITS_V1"
OUT = ROOT / "docs/review/science_boost/2026-10-26_external_circuits"

SUBSET = [
    ("mqt_bench", "bv", 4), ("mqt_bench", "bv", 8),
    ("mqt_bench", "ghz", 5), ("mqt_bench", "ghz", 10),
    ("mqt_bench", "qft", 4), ("mqt_bench", "qft", 8),
    ("mqt_bench", "dj", 4), ("mqt_bench", "dj", 8),
    ("mqt_bench", "wstate", 4), ("mqt_bench", "wstate", 8),
    ("mqt_bench", "qaoa", 4), ("mqt_bench", "qaoa", 8),
    ("mqt_bench", "grover", 4), ("mqt_bench", "grover", 8),
]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--deadline", type=float, default=60.0)
    parser.add_argument("--out-dir", type=Path, default=OUT)
    args = parser.parse_args()
    args.out_dir = args.out_dir.resolve()

    import mqt.bench
    from mqt.bench import get_benchmark, BenchmarkLevel

    rows: list[dict] = []
    started = time.perf_counter()
    for source, alg, n in SUBSET:
        try:
            raw = get_benchmark(alg, BenchmarkLevel.ALG, circuit_size=n)
        except Exception as exc:
            rows.append({"source": source, "algorithm": alg, "n_qubits": n,
                         "status": "GENERATION_FAILED", "reason": f"{type(exc).__name__}: {exc}"})
            continue
        normalized, meta = normalize_circuit(raw)
        if normalized is None:
            rows.append({"source": source, "algorithm": alg, "n_qubits": n,
                         "status": "NORMALIZATION_REFUSED", **meta})
            print(f"[refused] {alg} n={n}: {meta.get('reason')}", flush=True)
            continue
        state = None
        from experiments.e45_development_grid.run import state_from_circuit
        state = state_from_circuit(normalized)
        deadline = time.perf_counter() + args.deadline
        result = closure_run(state, deadline=deadline)
        final = result["final_state"]

        def counts(st):
            c = {"gates": len(st.gates)}
            for g in st.gates:
                c[g.name] = c.get(g.name, 0) + 1
            return c

        cr, cf = counts(state), counts(final)
        root_h = cr.get("h", 0)
        in_fragment = root_h == 0
        row = {
            "experiment_id": EXPERIMENT_ID,
            "source": source,
            "algorithm": alg,
            "n_qubits": n,
            "status": "OK",
            "raw_gates": raw.size(),
            "root_gates": cr["gates"],
            "root_rz": cr.get("rz", 0),
            "root_cx": cr.get("cx", 0),
            "root_h": root_h,
            "closure_gates": cf["gates"],
            "closure_rz": cf.get("rz", 0),
            "closure_cx": cf.get("cx", 0),
            "reduction_pct": round(100.0 * (cr["gates"] - cf["gates"]) / cr["gates"], 3) if cr["gates"] else 0.0,
            "closure_passes": result["passes"],
            "closure_truncated": result["truncated"],
            "closure_errors": result["errors"],
            "h_free": in_fragment,
        }
        if in_fragment:
            pp = phase_polynomial(state)
            ppf = phase_polynomial(final)
            support = pp["support_size"]
            support_final = ppf["support_size"]
            if support != support_final:
                raise SystemExit(f"E71_SUPPORT_INVARIANCE_FAIL:{alg}:{n}")
            row.update({
                "canonical_support": support,
                "gap_total_root": cr.get("rz", 0) - support,
                "gap_reorder": cr.get("rz", 0) - cf.get("rz", 0),
                "gap_content_final": cf.get("rz", 0) - support_final,
                "support_invariance": "PASS",
            })
        # persist the normalized listing for reproducibility
        qasm_path = args.out_dir / "instances" / f"{alg}_n{n}.qasm"
        qasm_path.parent.mkdir(parents=True, exist_ok=True)
        qasm_path.write_text(qasm2.dumps(normalized), encoding="utf-8", newline="\n")
        row["normalized_qasm"] = str(qasm_path.relative_to(args.out_dir))
        row["normalized_qasm_sha256"] = sha256(qasm_path)
        rows.append(row)
        print(f"[ok] {alg} n={n}: {cr['gates']} -> {cf['gates']} gates ({row['reduction_pct']}%)", flush=True)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    csv_path = args.out_dir / "external_circuit_results.csv"
    ok_rows = [r for r in rows if r.get("status") == "OK"]
    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        if rows:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()), lineterminator="\n")
            writer.writeheader()
            writer.writerows(rows)
    receipt = {
        "experiment_id": EXPERIMENT_ID,
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "mqt_bench_version": getattr(mqt.bench, "__version__", "2.3.0"),
        "subset": [list(s) for s in SUBSET],
        "rows": len(rows),
        "ok_count": len(ok_rows),
        "refused_count": sum(1 for r in rows if r.get("status") == "NORMALIZATION_REFUSED"),
        "failed_count": sum(1 for r in rows if r.get("status") == "GENERATION_FAILED"),
        "h_free_count": sum(1 for r in ok_rows if r.get("h_free")),
        "mean_reduction_pct": round(sum(r["reduction_pct"] for r in ok_rows) / len(ok_rows), 3) if ok_rows else None,
        "total_wall_seconds": round(time.perf_counter() - started, 1),
        "results_csv_sha256": sha256(csv_path),
        "closure_engine": "scripts/e56_closure_criterion.closure_run (same certified closure as E62)",
    }
    (args.out_dir / "receipt.json").write_text(
        json.dumps(receipt, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    print(json.dumps({k: receipt[k] for k in (
        "experiment_id", "ok_count", "refused_count", "mean_reduction_pct", "h_free_count",
    )}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
